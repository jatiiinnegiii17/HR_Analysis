CREATE TABLE hr_clean (
    employee_id INT,
    full_name VARCHAR(100),
    department VARCHAR(100),
    job_title VARCHAR(100),
    hire_date DATE,
    performance_rating DECIMAL(3,2),
    experience_years INT,
    status VARCHAR(50),
    work_mode VARCHAR(50),
    salary DECIMAL(12,2),
    country VARCHAR(100),
    city VARCHAR(100),
    age INT,
    job_level VARCHAR(50),
    hire_year INT
);
